"""Standalone repro for file-retrieval-corpus eval failures.

This script runs one flow turn against the corpus-rooted filesystem eval flow
and streams tool-call events so we can see how the agent searches before it
fails or answers.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
import uuid
from pathlib import Path
from typing import Any, Dict

from dotenv import load_dotenv

from athos.runtime.builder import build_config
from athos.runtime.runner import FlowRunner


DEFAULT_PROMPT = "What is the Perlmutter debug QOS time limit?"


def _emit_event(out_path: Path | None, payload: Dict[str, Any]) -> None:
    if out_path is None:
        return
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(payload, default=str) + "\n")


async def stream_once(
    *,
    config_path: str,
    flow_name: str,
    prompt: str,
    session_id: str,
    show_metadata: bool,
    out_path: Path | None,
    verbosity_level: int,
) -> None:
    cfg = build_config(config_path)
    runner = FlowRunner(cfg)

    print(f"config={config_path}")
    print(f"flow={flow_name}")
    print(f"session_id={session_id}")
    print(f"prompt_len={len(prompt)}")

    accumulated_text: list[str] = []
    try:
        async for chunk in runner.stream(
            flow_name=flow_name,
            message=prompt,
            session_id=session_id,
            user_id="example",
            interface="example",
            metadata={
                "reset_agent_memory": True,
                "source": "file_retrieval_corpus_repro",
                "verbosity_level": verbosity_level,
                "debug_include_steps": True,
            },
        ):
            meta = chunk.metadata or {}
            content = chunk.content or ""
            event_type = meta.get("event_type")

            if content:
                accumulated_text.append(content)
                sys.stdout.write(content)
                sys.stdout.flush()

            if event_type == "tool_call_start":
                print(f"\nTOOL_CALL_START: {meta.get('status_message')}")
            elif event_type == "tool_call_complete":
                print(f"\nTOOL_CALL_DONE: {meta.get('tool_name')}")
                print(f"TOOL_RESULT: {meta.get('tool_result')!r}")
            elif meta.get("error"):
                print(f"\nERROR: {content}")
            elif meta.get("final"):
                print("\n--- final_metadata ---")
                print(json.dumps(meta, indent=2, default=str))
                print("--- end final_metadata ---")

            if show_metadata and meta:
                print("\nMETADATA:")
                print(json.dumps(meta, indent=2, default=str))

            _emit_event(
                out_path,
                {
                    "content": content,
                    "metadata": meta,
                },
            )
    finally:
        await runner.cleanup()

    print("\n--- output_text ---")
    print("".join(accumulated_text))
    print("--- end output_text ---")


def main() -> None:
    load_dotenv()
    if not os.getenv("ATHOS_WORKSPACE"):
        raise RuntimeError(
            "ATHOS_WORKSPACE is not set. Export it or define it in .env before "
            "running this example."
        )

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="config/paper/cug_m1.yaml")
    parser.add_argument(
        "--flow",
        default="cug_lang_filesystem_gptoss",
    )
    parser.add_argument("--prompt", default=DEFAULT_PROMPT)
    parser.add_argument(
        "--session-id",
        default=None,
        help="Optional explicit session id; default is autogenerated.",
    )
    parser.add_argument(
        "--show-metadata",
        action="store_true",
        help="Print all chunk metadata for debugging.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="Optional JSONL output path for streamed events.",
    )
    parser.add_argument(
        "--verbosity-level",
        type=int,
        default=2,
        help="Execution verbosity override passed through flow metadata.",
    )
    args = parser.parse_args()

    session_id = args.session_id or f"repro-{args.flow}-{uuid.uuid4().hex[:8]}"
    asyncio.run(
        stream_once(
            config_path=args.config,
            flow_name=args.flow,
            prompt=args.prompt,
            session_id=session_id,
            show_metadata=args.show_metadata,
            out_path=args.out,
            verbosity_level=args.verbosity_level,
        )
    )


if __name__ == "__main__":
    main()
